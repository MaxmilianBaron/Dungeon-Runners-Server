        private static readonly Dictionary<string, GCNode> Definitions = CreateDefinitions();

        private static Dictionary<string, GCNode> CreateDefinitions()
        {
            var definitions = new Dictionary<string, GCNode>(StringComparer.OrdinalIgnoreCase);
            foreach (string name in Parents.Keys)
                definitions.Add(name, new GCNode { Name = name, CanonicalPath = name, NativeClassName = name, InheritanceResolved = true });
            return definitions;
        }

        internal static GCNode Resolve(string name)
        {
            return name != null && Definitions.TryGetValue(name, out GCNode definition) ? definition : null;
        }

        internal static bool IsDerivedFrom(string candidate, string expected)
        {
            if (candidate == null || expected == null || !Parents.ContainsKey(expected))
                return false;
            while (candidate != null && Parents.TryGetValue(candidate, out string parent))
            {
                if (string.Equals(candidate, expected, StringComparison.OrdinalIgnoreCase))
                    return true;
                candidate = parent;
            }
            return false;
        }
